def nav(active_page=None):
    parts = []
    for group, items in NAV_GROUPS:
        parts.append(f'<div class="group">{escape(group)}</div>')
        for href, label in items:
            cls = " on" if href == active_page else ""
            parts.append(f'<a href="{href}"{cls}>{escape(label)}</a>')
    parts.append(f'<a class="back" href="index.html">← Landing</a>')
    return f'<div class="navwrap"><nav>{"".join(parts)}</nav></div>'

